package com.databricks.sql.transaction.tahoe.rapids

import com.databricks.sql.transaction.tahoe.{OptimisticTransaction, RowTracking}
import com.databricks.sql.transaction.tahoe.actions.{AddFile, FileAction}
import com.databricks.sql.transaction.tahoe.commands.{DeletionVectorUtils, TouchedFileWithDV, UpdateCommand}
import com.databricks.sql.transaction.tahoe.files.TahoeBatchFileIndex
import com.databricks.sql.transaction.tahoe.files.TahoeFileIndex

import org.apache.spark.sql.{DataFrame, SparkSession}
import org.apache.spark.sql.catalyst.expressions.{Expression, InputFileBlockLength,
  InputFileBlockStart, InputFileName}
import org.apache.spark.sql.catalyst.plans.logical.LogicalPlan
import org.apache.spark.sql.functions.input_file_name
import org.apache.spark.sql.nvidia.DFUDFShims
import org.apache.spark.storage.StorageLevel

case class GpuUpdateCommand(
    gpuDeltaLog: GpuDeltaLog,
    tahoeFileIndex: TahoeFileIndex,
    target: LogicalPlan,
    updateExpressions: Seq[Expression],
    condition: Option[Expression])
    extends GpuUpdateCommandBase(
      gpuDeltaLog,
      tahoeFileIndex,
      target,
      updateExpressions,
      condition) {

  private val CacheStorageBudgetDivisor = 4
  private val CacheMatchFractionDivisor = 4

  private def usesInputFileInformation(expr: Expression): Boolean = expr match {
    case _: InputFileName | _: InputFileBlockStart | _: InputFileBlockLength => true
    case _ => expr.children.exists(usesInputFileInformation)
  }

  private class DbrPersistentDvTouchedFiles(
      val touchedFiles: Seq[TouchedFileWithDV],
      override val matchedRows: Option[DataFrame]) extends PersistentDvTouchedFiles {
    override val files: Seq[AddFile] = touchedFiles.map(_.fileLogEntry)
    override def release(): Unit = matchedRows.foreach(_.unpersist(blocking = true))
  }

  override protected def findTouchedFilesWithPersistentDVs(
      sparkSession: SparkSession,
      txn: OptimisticTransaction,
      candidateFiles: Seq[AddFile],
      fileIndex: TahoeBatchFileIndex,
      updateCondition: Expression,
      nameToAddFileMap: Map[String, AddFile]):
      Option[PersistentDvTouchedFiles] = {
    val targetScan = DMLWithDeletionVectorsHelperShims.createTargetDfForGpuScanningForMatches(
      sparkSession, target, fileIndex)
    val recordCounts = candidateFiles.map(_.numLogicalRecords)
    val candidateRows = if (recordCounts.forall(_.isDefined)) {
      Some(recordCounts.flatten.iterator.map(BigInt(_)).sum)
    } else {
      None
    }
    // Spark's storage manager bounds MEMORY_ONLY cache blocks and evicts them instead of using
    // local disk. Admit only a small fraction of currently free worker storage; without complete
    // row counts, the broad-match check below cannot safely retain the cache. That check
    // follows the bitmap scan because an exact pre-count would add a full scan to every
    // selective UPDATE, negating the benefit of reusing its filtered rows.
    // Local mode runs its executor in the driver JVM, so its single storage entry is usable.
    // On a cluster, exclude one entry for the driver; dropping the largest is conservative
    // even when the driver is not the largest entry.
    val sparkContext = sparkSession.sparkContext
    val storageFreeBytes = sparkContext.getExecutorMemoryStatus.values.map(_._2).toSeq.sorted
    val localMode = sparkContext.master == "local" || sparkContext.master.startsWith("local[")
    val workerStorageFreeBytes = if (localMode) storageFreeBytes else storageFreeBytes.dropRight(1)
    val freeWorkerStorageBytes = workerStorageFreeBytes.iterator.map(BigInt(_)).sum
    val candidateBytes = candidateFiles.iterator.map(file => BigInt(file.size)).sum
    val cacheFits = candidateBytes > 0 &&
      candidateBytes <= freeWorkerStorageBytes / CacheStorageBudgetDivisor
    // A cached filtered scan is safe only when its row set is stable and no hidden row-tracking
    // or CDF columns must be regenerated by the standard rewrite path.
    val matchedRows = if (cacheFits && candidateRows.exists(_ > 0) &&
        updateCondition.deterministic &&
        !updateExpressions.exists(usesInputFileInformation) &&
        !RowTracking.isEnabled(txn.protocol, txn.metadata) &&
        !UpdateCommand.shouldOutputCdc(txn)) {
      Some(targetScan.dataFrameWithoutFilePath
        .filter(DFUDFShims.exprToColumn(updateCondition))
        .withColumn(targetScan.filePathColumnName, input_file_name())
        .persist(StorageLevel.MEMORY_ONLY))
    } else {
      None
    }
    try {
      val touchedFiles = GpuDeletionVectorBitmapGenerator.findTouchedFilesWithGpuBitmap(
        sparkSession,
        txn,
        hasReadableDVs = DeletionVectorUtils.deletionVectorsReadable(txn.snapshot),
        targetScan,
        DFUDFShims.exprToColumn(updateCondition),
        nameToAddFileMap,
        prefilteredTargetDf = matchedRows)
      val matchedRowCount = touchedFiles.iterator.map { file =>
        BigInt(file.numberOfModifiedRows)
      }.sum
      val reuseCache = matchedRows.isDefined && candidateRows.exists { totalRows =>
        matchedRowCount <= totalRows / CacheMatchFractionDivisor
      }
      if (!reuseCache) {
        matchedRows.foreach(_.unpersist(blocking = true))
      }
      Some(new DbrPersistentDvTouchedFiles(touchedFiles,
        if (reuseCache) matchedRows else None))
    } catch {
      case t: Throwable =>
        matchedRows.foreach(_.unpersist(blocking = true))
        throw t
    }
  }

  override protected def processUnmodifiedDataWithPersistentDVs(
      sparkSession: SparkSession,
      txn: OptimisticTransaction,
      touchedFiles: PersistentDvTouchedFiles):
      Option[(Seq[FileAction], Map[String, Long])] = touchedFiles match {
    case dbTouchedFiles: DbrPersistentDvTouchedFiles =>
      Some(GpuDeletionVectorBitmapGenerator.processUnmodifiedData(
        sparkSession, dbTouchedFiles.touchedFiles, txn))
    case other =>
      throw new IllegalStateException(
        s"Unexpected persistent-DV touched-file container: ${other.getClass.getName}")
  }
}
